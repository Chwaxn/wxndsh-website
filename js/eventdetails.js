/* ========================================
   GET EVENT ID FROM URL
======================================== */

var pageURL = new URLSearchParams(window.location.search);

var selectedEventID = pageURL.get("id");



/* ========================================
   GET EVENT DETAILS ELEMENTS
======================================== */

var eventBannerImage =
    document.getElementById("EventBannerImage");

var eventCategory =
    document.getElementById("EventCategory");

var eventTitle =
    document.getElementById("EventTitle");

var eventDescription =
    document.getElementById("EventDescription");

var eventLocation =
    document.getElementById("EventLocation");

var eventDate =
    document.getElementById("EventDate");

var eventTime =
    document.getElementById("EventTime");

var eventOrganiser =
    document.getElementById("EventOrganiser");



/* ========================================
   CURRENT WEBSITE LANGUAGE
======================================== */

var currentLanguage =
    localStorage.getItem("wxndshLanguage") || "en";



/* ========================================
   DISPLAY SELECTED EVENT
======================================== */

function displaySelectedEvent(){


    /* ========================================
       CHECK SELECTED EVENT
    ========================================= */

    var selectedEvent =
        eventDetailsData[selectedEventID];


    if(!selectedEvent){

        displayEventNotFound();

        return;

    }



    /* ========================================
       CHANGE PAGE TITLE
    ========================================= */

    document.title =
        selectedEvent.title + " | WXNDSH";



    /* ========================================
       DISPLAY EVENT BANNER
    ========================================= */

    eventBannerImage.src =
        selectedEvent.image;

    eventBannerImage.alt =
        selectedEvent.imageAlt;



    /* ========================================
       DISPLAY EVENT CATEGORY
    ========================================= */

    eventCategory.textContent =
        selectedEvent.category;

    eventCategory.setAttribute(
        "data-category",
        selectedEvent.categoryValue
    );



    /* ========================================
       DISPLAY EVENT TITLE
    ========================================= */

    eventTitle.textContent =
        selectedEvent.title;



    /* ========================================
       DISPLAY EVENT INFORMATION
    ========================================= */

    eventLocation.textContent =
        selectedEvent.location;

    eventTime.textContent =
        selectedEvent.time;

    eventOrganiser.textContent =
        selectedEvent.organiser;



    /* ========================================
       DISPLAY EVENT LANGUAGE
    ========================================= */

    updateEventLanguage();


}



/* ========================================
   DISPLAY EVENT NOT FOUND
======================================== */

function displayEventNotFound(){


    /* ========================================
       CHANGE PAGE TITLE
    ========================================= */

    document.title =
        "Event Not Found | WXNDSH";



    /* ========================================
       DISPLAY PLACEHOLDER BANNER
    ========================================= */

    eventBannerImage.src =
        "img/event-placeholder.jpg";

    eventBannerImage.alt =
        "Event Not Found";



    /* ========================================
       DISPLAY EVENT NOT FOUND CONTENT
    ========================================= */

    eventCategory.textContent =
        "EVENT";

    eventCategory.setAttribute(
        "data-category",
        "entertainment"
    );

    eventTitle.textContent =
        currentLanguage === "ms"
            ? "Event Tidak Ditemui"
            : "Event Not Found";

    eventDescription.textContent =
        currentLanguage === "ms"
            ? "Maklumat event ini tidak dapat ditemui. Sila kembali ke halaman utama dan pilih event yang tersedia."
            : "The information for this event could not be found. Please return to the homepage and select an available event.";

    eventLocation.textContent =
        "-";

    eventDate.textContent =
        "-";

    eventTime.textContent =
        "-";

    eventOrganiser.textContent =
        "-";


}



/* ========================================
   UPDATE EVENT LANGUAGE
======================================== */

function updateEventLanguage(){


    /* ========================================
       GET SELECTED EVENT
    ========================================= */

    var selectedEvent =
        eventDetailsData[selectedEventID];


    if(!selectedEvent){

        displayEventNotFound();

        return;

    }



    /* ========================================
       ENGLISH LANGUAGE
    ========================================= */

    if(currentLanguage === "en"){

        eventDescription.textContent =
            selectedEvent.descriptionEnglish;

        eventDate.textContent =
            selectedEvent.dateEnglish;

    }



    /* ========================================
       MALAY LANGUAGE
    ========================================= */

    else{

        eventDescription.textContent =
            selectedEvent.descriptionMalay;

        eventDate.textContent =
            selectedEvent.dateMalay;

    }


}



/* ========================================
   LANGUAGE ELEMENTS
======================================== */

var languageButton =
    document.getElementById("LanguageButton");

var languageFlag =
    document.getElementById("LanguageFlag");

var languageText =
    document.getElementById("LanguageText");

var translationElements =
    document.querySelectorAll("[data-en][data-ms]");



/* ========================================
   UPDATE WEBSITE LANGUAGE
======================================== */

function updateWebsiteLanguage(){


    /* ========================================
       UPDATE TRANSLATED ELEMENTS
    ========================================= */

    translationElements.forEach(function(element){

        if(currentLanguage === "en"){

            element.textContent =
                element.getAttribute("data-en");

        }

        else{

            element.textContent =
                element.getAttribute("data-ms");

        }

    });



    /* ========================================
       UPDATE LANGUAGE BUTTON
    ========================================= */

    if(currentLanguage === "en"){

        languageText.textContent =
            "EN";

        languageFlag.src =
            "img/uk flag.png";

        languageFlag.alt =
            "English Language";

        document.documentElement.lang =
            "en";

    }

    else{

        languageText.textContent =
            "BM";

        languageFlag.src =
            "img/malay flag.png";

        languageFlag.alt =
            "Bahasa Melayu";

        document.documentElement.lang =
            "ms";

    }



    /* ========================================
       UPDATE EVENT CONTENT
    ========================================= */

    updateEventLanguage();


}



/* ========================================
   LANGUAGE BUTTON CLICK
======================================== */

if(languageButton){

    languageButton.addEventListener(
        "click",
        function(){


            /* ========================================
               CHANGE CURRENT LANGUAGE
            ========================================= */

            if(currentLanguage === "en"){

                currentLanguage =
                    "ms";

            }

            else{

                currentLanguage =
                    "en";

            }



            /* ========================================
               SAVE CURRENT LANGUAGE
            ========================================= */

            localStorage.setItem(
                "wxndshLanguage",
                currentLanguage
            );



            /* ========================================
               UPDATE WEBSITE
            ========================================= */

            updateWebsiteLanguage();


        }
    );

}



/* ========================================
   MOBILE MENU
======================================== */

var mobileMenuButton =
    document.getElementById("MobileMenuButton");

var headerNavigation =
    document.getElementById("HeaderNavigation");



/* ========================================
   MOBILE MENU BUTTON CLICK
======================================== */

if(
    mobileMenuButton &&
    headerNavigation
){

    mobileMenuButton.addEventListener(
        "click",
        function(){


            /* ========================================
               TOGGLE MOBILE NAVIGATION
            ========================================= */

            headerNavigation.classList.toggle(
                "ShowNavigation"
            );



            /* ========================================
               UPDATE MENU ACCESSIBILITY
            ========================================= */

            var menuIsOpen =
                headerNavigation.classList.contains(
                    "ShowNavigation"
                );

            mobileMenuButton.setAttribute(
                "aria-expanded",
                menuIsOpen
            );


        }
    );

}



/* ========================================
   CLOSE MOBILE MENU AFTER LINK CLICK
======================================== */

var navigationLinks =
    document.querySelectorAll(
        "#HeaderNavigation a"
    );


navigationLinks.forEach(function(link){

    link.addEventListener(
        "click",
        function(){


            if(
                headerNavigation &&
                mobileMenuButton
            ){

                headerNavigation.classList.remove(
                    "ShowNavigation"
                );

                mobileMenuButton.setAttribute(
                    "aria-expanded",
                    "false"
                );

            }


        }
    );

});



/* ========================================
   BACK TO TOP BUTTON
======================================== */

var backToTopButton =
    document.getElementById("BackToTopButton");



/* ========================================
   SHOW OR HIDE BACK TO TOP BUTTON
======================================== */

function updateBackToTopButton(){


    if(!backToTopButton){

        return;

    }



    if(window.scrollY > 350){

        backToTopButton.classList.add(
            "ShowBackToTop"
        );

    }

    else{

        backToTopButton.classList.remove(
            "ShowBackToTop"
        );

    }


}



/* ========================================
   PAGE SCROLL
======================================== */

window.addEventListener(
    "scroll",
    updateBackToTopButton
);



/* ========================================
   BACK TO TOP BUTTON CLICK
======================================== */

if(backToTopButton){

    backToTopButton.addEventListener(
        "click",
        function(){


            window.scrollTo({

                top:0,

                behavior:"smooth"

            });


        }
    );

}



